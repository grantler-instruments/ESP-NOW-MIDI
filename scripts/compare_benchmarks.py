#!/usr/bin/env python3
"""Compares round-trip benchmarks between library versions, as a Markdown report.

Reads the raw round-trip files (not the *_analysis.txt files), for each
condition (<distance>m_obstacles-<n>) of one transport:

- a directory <condition>/ with round*.txt files (benchmark_rtt.py --rounds), or
- a single file <condition>.txt (older runs).

If both exist, the directory wins. Runs not timed in Python (Pd's timer, about
5.3 ms steps) are marked; their IQR/MAD-style fine detail is meaningless.

Usage:
  python3 scripts/compare_benchmarks.py                 # all versions, espnowMidi
  python3 scripts/compare_benchmarks.py 0.10.8 0.19.1 --out report.md
"""
import argparse
import re
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from analyze_benchmark import (  # noqa: E402
    JITTER_BUCKETS, jitter_metrics, parse_header, parse_values, percentile, round_files,
)

ROOT = Path(__file__).resolve().parent.parent
CONDITION = re.compile(r"^(\d+(?:\.\d+)?)m_obstacles-(\d+)$")


def version_key(name):
    return tuple(int(x) if x.isdigit() else 0 for x in name.split("."))


def load(transport_dir):
    """{condition: (series, lost, timer)} for one version/transport."""
    found = {}
    if not transport_dir.is_dir():
        return found
    for path in transport_dir.iterdir():
        name = path.stem if path.is_file() else path.name
        if not CONDITION.match(name):
            continue
        if path.is_dir():
            files = round_files(path)
            if not files:
                continue
            series = [parse_values(f) for f in files]
            lost = sum(int(parse_header(f).get("lost", 0)) for f in files)
            timer = parse_header(files[0]).get("timer", "pd")
            found[name] = (series, lost, timer)
        elif path.suffix == ".txt" and name not in found:
            header = parse_header(path)
            found[name] = ([parse_values(path)], int(header.get("lost", 0)) if "lost" in header else None,
                           header.get("timer", "pd"))
    return found


def condition_key(name):
    m = CONDITION.match(name)
    return float(m.group(1)), int(m.group(2))


def share(pct):
    return "<0.1 %" if 0 < pct < 0.05 else f"{pct:.1f} %"


def row(version, series, lost, timer):
    pooled = sorted(v for values in series for v in values)
    j = jitter_metrics(series)
    median = statistics.median(pooled)
    timer_note = "" if "perf_counter" in timer else " ¹"
    lost_text = "?" if lost is None else str(lost)
    return (f"| {version}{timer_note} | {len(pooled)} | {lost_text} | {statistics.fmean(pooled):.2f} | {median:.2f} | "
            f"{percentile(pooled, 0.95):.2f} | {percentile(pooled, 0.99):.2f} | {pooled[-1]:.2f} | "
            f"{statistics.stdev(pooled):.2f} | {j['p95_minus_median']:.2f} | {j['consecutive_delta']:.2f} | "
            f"{j['late_10ms_pct']:.1f} |"), j


def report(versions, transport):
    data = {v: load(ROOT / "benchmarks" / v / transport) for v in versions}
    conditions = sorted({c for d in data.values() for c in d}, key=condition_key)
    lines = [f"# Round-trip comparison: {transport}", "",
             f"Versions: {', '.join(versions)}. All times in ms. "
             "Generated by `scripts/compare_benchmarks.py`.", "",
             "- sigma: standard deviation",
             "- p95−med: how much later the slowest 5 % arrive than a typical message",
             "- Δconsec: mean change between two consecutive round trips (felt unevenness)",
             "- late>10: % of messages more than 10 ms over the median",
             "- ¹ timed in Pd (about 5.3 ms steps): medians are rounded to a step, "
             "fine detail is not comparable", ""]
    bucket_names = [f">{lo}" if hi == float("inf") else f"{lo}–{hi}" for lo, hi in JITTER_BUCKETS]
    for condition in conditions:
        distance, obstacles = condition_key(condition)
        lines += [f"## {distance:g} m, {obstacles} obstacle{'s' if obstacles != 1 else ''}", "",
                  "| version | samples | lost | mean | median | p95 | p99 | max | sigma | p95−med | Δconsec | late>10 % |",
                  "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        buckets = []
        for v in versions:
            if condition in data[v]:
                text, j = row(v, *data[v][condition])
                lines.append(text)
                buckets.append((v, [j[k] for k in j if k.startswith("bucket_")]))
        lines += ["", "Share of round trips per range (ms):", "",
                  "| version | " + " | ".join(bucket_names) + " |",
                  "|---|" + "---|" * len(bucket_names)]
        lines += [f"| {v} | " + " | ".join(share(b) for b in bs) + " |" for v, bs in buckets]
        lines.append("")
    return "\n".join(lines)


def main():
    p = argparse.ArgumentParser(description="Compare round-trip benchmarks between versions.")
    p.add_argument("versions", nargs="*", help="default: every directory in benchmarks/")
    p.add_argument("--transport", default="espnowMidi")
    p.add_argument("--out", type=Path, help="write the report here instead of printing it")
    args = p.parse_args()
    versions = args.versions or sorted(
        (d.name for d in (ROOT / "benchmarks").iterdir() if d.is_dir() and d.name[0].isdigit()),
        key=version_key)
    text = report(versions, args.transport)
    if args.out:
        args.out.write_text(text + "\n", encoding="utf-8")
        print(f"written: {args.out}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
